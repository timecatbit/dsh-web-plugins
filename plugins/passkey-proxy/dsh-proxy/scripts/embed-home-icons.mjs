// Regenerate src/home-icons.ts from the PNGs in assets/home-icons.
// The PNGs are rendered from DSH's own favicon path by render-home-icons.cjs
// (needs Playwright + Chrome; not a dependency of this package).
import { readFileSync, writeFileSync } from 'node:fs'

const variants = ['black', 'white']
const files = ['apple-touch-icon', 'icon-192', 'icon-512', 'icon-maskable-512']
const body = variants.map(v => `  ${v}: {\n${files.map(f =>
  `    '/${f}.png': '${readFileSync(new URL(`../assets/home-icons/${v}-${f}.png`, import.meta.url)).toString('base64')}',`
).join('\n')}\n  },`).join('\n')

writeFileSync(new URL('../src/home-icons.ts', import.meta.url), `/**
 * Black-and-white DeepSeek whale icons the proxy can serve in place of DSH's
 * own home-screen icons (\`homeScreenIcon\` setting). Rendered from the whale
 * path in DSH's favicon.svg. GENERATED by scripts/embed-home-icons.mjs from
 * assets/home-icons — do not edit by hand.
 */
import type { HomeScreenIcon } from './contract.ts'

const PNG_BASE64: Record<Exclude<HomeScreenIcon, 'dsh'>, Record<string, string>> = {
${body}
}

const decoded = new Map<string, Buffer>()

/**
 * The replacement PNG for one icon path, or undefined when DSH's own icon
 * should be served (the \`dsh\` choice, or a path that is not a home-screen icon).
 */
export function homeScreenIconPng(choice: HomeScreenIcon | undefined, pathname: string): Buffer | undefined {
  if (choice !== 'black' && choice !== 'white') return undefined
  const base64 = PNG_BASE64[choice][pathname]
  if (base64 === undefined) return undefined
  const key = choice + pathname
  let png = decoded.get(key)
  if (png === undefined) {
    png = Buffer.from(base64, 'base64')
    decoded.set(key, png)
  }
  return png
}
`)
